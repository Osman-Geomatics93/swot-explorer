/**
 * Export a selection as a URL list or a download script.
 * Scripts read the token from the EDL_TOKEN environment variable and never embed it.
 */
import type { Feature, MultiPolygon, Polygon } from 'geojson';

export interface ScriptFile {
  url: string;
  /** Relative output path, e.g. SWOT_L2_HR_PIXC_D/<file>.nc */
  path: string;
}

export function urlList(files: ScriptFile[]): string {
  return files.map((f) => f.url).join('\n') + '\n';
}

export function bashScript(files: ScriptFile[]): string {
  const lines = files.map((f) => `fetch ${JSON.stringify(f.url)} ${JSON.stringify(f.path)}`);
  return `#!/usr/bin/env bash
# SWOT download script generated by SWOT Explorer (${new Date().toISOString()}).
# Set your Earthdata token first:  export EDL_TOKEN="..."
set -euo pipefail
: "\${EDL_TOKEN:?Set EDL_TOKEN to your Earthdata Login token}"

fetch() {
  mkdir -p "$(dirname "$2")"
  if [ -s "$2" ]; then echo "skip $2"; return; fi
  curl --fail --location --retry 3 --header "Authorization: Bearer $EDL_TOKEN" --output "$2.part" "$1"
  mv "$2.part" "$2"
}

${lines.join('\n')}
`;
}

export function powershellScript(files: ScriptFile[]): string {
  const rows = files.map((f) => `  @{ Url = '${f.url}'; Path = '${f.path.replace(/\//g, '\\')}' }`).join(",\n");
  return `# SWOT download script generated by SWOT Explorer (${new Date().toISOString()}).
# Set your Earthdata token first:  $env:EDL_TOKEN = "..."
if (-not $env:EDL_TOKEN) { throw 'Set $env:EDL_TOKEN to your Earthdata Login token' }
$headers = @{ Authorization = "Bearer $env:EDL_TOKEN" }
$files = @(
${rows}
)
foreach ($f in $files) {
  if ((Test-Path $f.Path) -and (Get-Item $f.Path).Length -gt 0) { "skip $($f.Path)"; continue }
  New-Item -ItemType Directory -Force (Split-Path $f.Path) | Out-Null
  Invoke-WebRequest -Uri $f.Url -Headers $headers -OutFile "$($f.Path).part"
  Move-Item -Force "$($f.Path).part" $f.Path
}
`;
}

/** Python script that clips downloaded NetCDF granules (PIXC, Raster, LR SSH) to the study area. */
export function pythonClipScript(area: Feature<Polygon | MultiPolygon>, files: ScriptFile[], productLabel: string): string {
  return `"""Clip SWOT ${productLabel} NetCDF files to the study area.

Generated by SWOT Explorer (${new Date().toISOString()}).
Run after downloading the files (download.sh / download.ps1) in the same folder.
Requires: pip install xarray netCDF4 shapely numpy
"""
import json
from pathlib import Path

import numpy as np
import xarray as xr
from shapely import contains_xy
from shapely.geometry import shape

AREA = shape(json.loads(${JSON.stringify(JSON.stringify(area.geometry))}))
FILES = ${JSON.stringify(files.map((f) => f.path), null, 2)}
OUT = Path("clipped")
OUT.mkdir(exist_ok=True)


def find_lonlat(ds):
    """Return (lon, lat) arrays from the group's coordinate variables."""
    for lon, lat in (("longitude", "latitude"), ("lon", "lat")):
        if lon in ds.variables and lat in ds.variables:
            return ds[lon], ds[lat]
    raise KeyError("no longitude/latitude variables")


def clip_group(ds):
    lon, lat = find_lonlat(ds)
    lon_v = ((lon.values + 180) % 360) - 180
    inside = contains_xy(AREA, lon_v, lat.values)
    if not inside.any():
        return None
    dims = lon.dims
    if len(dims) == 1:  # point data (PIXC): keep the points inside the area
        return ds.isel({dims[0]: np.nonzero(inside)[0]})
    # gridded / swath data: crop to the area's index window, then blank cells outside it
    window = {d: slice(int(i.min()), int(i.max()) + 1) for d, i in zip(dims, np.nonzero(inside))}
    out = ds.isel(window)
    mask = xr.DataArray(inside[tuple(window.values())], dims=dims)
    for name, var in out.data_vars.items():
        if set(dims) <= set(var.dims) and var.dtype.kind in "fiu":
            out[name] = var.where(mask)
    return out


for path in FILES:
    src = Path(path)
    if not src.exists():
        print("missing", src)
        continue
    # PIXC keeps its data in the 'pixel_cloud' group; Raster and LR SSH use the root group.
    group = "pixel_cloud" if "_PIXC_" in src.name else None
    with xr.open_dataset(src, group=group, mask_and_scale=True) as ds:
        out = clip_group(ds)
    if out is None:
        print("no data inside area:", src.name)
        continue
    dst = OUT / src.name.replace(".nc", "_clipped.nc")
    out.to_netcdf(dst)
    print("wrote", dst, dict(out.sizes))
`;
}

export async function saveText(filename: string, text: string, type = 'text/plain'): Promise<void> {
  const url = URL.createObjectURL(new Blob([text], { type }));
  try {
    await browser.downloads.download({ url, filename, conflictAction: 'uniquify' });
  } finally {
    setTimeout(() => URL.revokeObjectURL(url), 60_000);
  }
}
